local function describe(record)
  local parts = {}
  for k, step in ipairs(record.steps) do
    local label = Game.step_label(step)
    local ck, time = step[1], step[2]
    if ck == CK.LEVER_OFF then
      label = label .. " (then let go)"
    elseif ck == CK.CHARGE then
      label = label .. " (hold " .. (step[3] + 1) .. "f)"
    elseif k > 1 and Game.TIMED[ck] and time > 0 then
      label = label .. " (" .. time .. "f)"
    elseif ck == CK.ROTATE then
      label = label .. " (within " .. time .. "f)"
    end
    table.insert(parts, label)
  end
  return table.concat(parts, " · ")
end

local function buttons(record)
  local index = bits.band(record.btix, C.BT_INDEX)
  if index == C.BT_PRESS_OR_RELEASE then
    return "press or release"
  end
  if index == C.BT_PRESS then
    return "press"
  end
  return "held"
end

print("# Motion windows by character")
print("")
print(
  "Generated by `tools/windows_table.lua` from the command tables in the program ROM. Each step's number is how many frames it may come after the previous step; `(then let go)` steps count the next window from letting go. The button may come on the frame the motion completes or up to `reset - 2` frames later (10 for almost every move). `~2` means any direction that includes down (1, 2 or 3); `[4]` is a charge. Charge and 360 moves are graded too, with less specific feedback than motions."
)
for row = 0, 20 do
  local f = commands.fighters[row]
  print("")
  print("## " .. NAMES[f.name])
  print("")
  print("| Move | Input | Steps and windows | Button after motion | Button |")
  print("| --- | --- | --- | --- | --- |")
  local slots = {}
  for slot, record in pairs(f.slots) do
    if slot >= C.SA_GROUND and record.steps[1][1] ~= CK.NONE and bits.band(record.btix, C.BT_INDEX) ~= C.BT_NONE then
      table.insert(slots, slot)
    end
  end
  table.sort(slots)
  local seen = {}
  for _, slot in ipairs(slots) do
    local r = f.slots[slot]
    local key = r.name .. r.notation
    if not seen[key] then
      seen[key] = true
      print(
        string.format(
          "| %s%s | %s | %s | %df | %s |",
          r.name,
          r.guess and " (?)" or "",
          r.notation,
          describe(r),
          r.reset - 2,
          buttons(r)
        )
      )
    end
  end
end
